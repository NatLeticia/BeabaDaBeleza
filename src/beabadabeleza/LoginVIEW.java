    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
         try {
            // 1. Pega os dados dos campos que você desenhou
            String email_usuario = txtUsuario1.getText(); // Se o nome da sua caixa de texto for outro, troque aqui
            String senha_usuario = new String(txtSenha.getPassword()); // Mesma coisa para a caixa de senha
            
            // 2. Guarda na DTO
            UsuarioDTO objusuario = new UsuarioDTO();
            objusuario.setEmail(email_usuario);
            objusuario.setSenha(senha_usuario);
            
            // 3. Verifica no seu novo banco beaba_da_beleza
            UsuarioDAO objusuariodao = new UsuarioDAO();
            java.sql.ResultSet rsusuariodao = objusuariodao.autenticacaoUsuario(objusuario);
            
            // 4. Se a senha e email estiverem corretos, entra!
            if (rsusuariodao.next()) {
                HomeVIEW telaHome = new HomeVIEW();
                telaHome.setVisible(true);
                this.dispose(); // Fecha o login
            } else {
                javax.swing.JOptionPane.showMessageDialog(null, "E-mail ou Senha inválida!");
            }
        } catch (Exception erro) {
            javax.swing.JOptionPane.showMessageDialog(null, "Erro na View: " + erro.getMessage());
        }

    }//GEN-LAST:event_btnEntrarActionPerformed

